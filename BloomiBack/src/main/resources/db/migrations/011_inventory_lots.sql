-- Apply after backup, with the backend stopped. Opening balances use today's known
-- reference cost, never reconstructed purchase origins or historical sale costs.
BEGIN;
LOCK TABLE product IN SHARE ROW EXCLUSIVE MODE;
CREATE TABLE IF NOT EXISTS inventory_lot (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 product_id BIGINT NOT NULL REFERENCES product(id),
 source_key VARCHAR(100) NOT NULL, reference VARCHAR(160) NOT NULL,
 opening BOOLEAN NOT NULL, received_on DATE NOT NULL, received_at TIMESTAMPTZ NOT NULL,
 remaining INTEGER NOT NULL CHECK(remaining>=0), unit_cost NUMERIC(14,2) CHECK(unit_cost>=0),
 CONSTRAINT uk_lot_product_source UNIQUE(product_id,source_key)
);
CREATE INDEX IF NOT EXISTS idx_lot_fifo ON inventory_lot(product_id,opening DESC,received_on,received_at,source_key);
ALTER TABLE sale_item ADD COLUMN IF NOT EXISTS cost_total NUMERIC(24,2);
CREATE TABLE IF NOT EXISTS sale_cost_allocation (
 sale_item_id BIGINT NOT NULL REFERENCES sale_item(id), sort_order INTEGER NOT NULL,
 source_key VARCHAR(100) NOT NULL, reference VARCHAR(160) NOT NULL,
 opening BOOLEAN NOT NULL, received_on DATE NOT NULL, received_at TIMESTAMPTZ NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity>0), unit_cost NUMERIC(14,2) CHECK(unit_cost>=0),
 PRIMARY KEY(sale_item_id,sort_order)
);
INSERT INTO inventory_lot(created_at,updated_at,product_id,source_key,reference,opening,received_on,received_at,remaining,unit_cost)
 SELECT CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,p.id,'opening','Saldo inicial',true,
 (CURRENT_TIMESTAMP AT TIME ZONE 'America/Bogota')::date,CURRENT_TIMESTAMP,p.stock,
 CASE WHEN p.cost_confirmed THEN p.purchase_price ELSE NULL END
 FROM product p WHERE NOT EXISTS(SELECT 1 FROM inventory_lot l WHERE l.product_id=p.id);
COMMIT;
