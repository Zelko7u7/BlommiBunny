-- Additive. Existing sales stay unreviewed; no payments or authorizations are inferred.
BEGIN;
ALTER TABLE sale ADD COLUMN IF NOT EXISTS payments_reviewed BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE sale ADD COLUMN IF NOT EXISTS collection_authorized BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE sale ADD COLUMN IF NOT EXISTS collection_authorized_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE sale ADD COLUMN IF NOT EXISTS collection_authorized_by VARCHAR(80);
ALTER TABLE sale ADD COLUMN IF NOT EXISTS payments_changed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE sale ADD COLUMN IF NOT EXISTS payments_reviewed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE sale ADD COLUMN IF NOT EXISTS payments_reviewed_by VARCHAR(80);
CREATE TABLE IF NOT EXISTS sale_payment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 sale_id BIGINT NOT NULL REFERENCES sale(id),
 request_id UUID NOT NULL UNIQUE,
 request_fingerprint VARCHAR(64) NOT NULL,
 amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
 payment_date DATE NOT NULL,
 payment_method VARCHAR(20) NOT NULL,
 reference VARCHAR(120), notes VARCHAR(500), recorded_by VARCHAR(80) NOT NULL,
 cancelled BOOLEAN NOT NULL DEFAULT false,
 cancelled_at TIMESTAMP WITH TIME ZONE, cancellation_reason VARCHAR(500), cancelled_by VARCHAR(80)
);
CREATE INDEX IF NOT EXISTS idx_sale_payment_sale ON sale_payment(sale_id);
CREATE TABLE IF NOT EXISTS sale_collection_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 sale_id BIGINT NOT NULL REFERENCES sale(id),
 action VARCHAR(20) NOT NULL, reason VARCHAR(500) NOT NULL, recorded_by VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sale_collection_event_sale ON sale_collection_event(sale_id);
CREATE INDEX IF NOT EXISTS idx_sale_collection_date ON sale(collection_authorized_at) WHERE collection_authorized=true AND cancelled=false;
COMMIT;
