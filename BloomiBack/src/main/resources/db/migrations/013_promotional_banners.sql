-- Additive migration. Back up first; originals and commercial tables are preserved.
BEGIN;
SET LOCAL lock_timeout='10s';
CREATE TABLE IF NOT EXISTS promotional_banner (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 internal_name VARCHAR(120) NOT NULL,
 desktop_image_url VARCHAR(500) NOT NULL,
 desktop_image_public_id VARCHAR(200) NOT NULL,
 desktop_width INTEGER NOT NULL CHECK(desktop_width>0),desktop_height INTEGER NOT NULL CHECK(desktop_height>0),
 mobile_image_url VARCHAR(500),mobile_image_public_id VARCHAR(200),mobile_width INTEGER,mobile_height INTEGER,
 alt_text VARCHAR(240) NOT NULL,headline VARCHAR(120),description VARCHAR(240),
 target_type VARCHAR(20) NOT NULL CHECK(target_type IN ('CATALOG','CATEGORY','PRODUCT','SECTION')),
 category_id BIGINT REFERENCES category(id) ON DELETE SET NULL,
 product_id BIGINT REFERENCES product(id) ON DELETE SET NULL,
 section VARCHAR(20) CHECK(section IN ('ABOUT','FAVORITES')),
 sort_order INTEGER NOT NULL CHECK(sort_order>=0),active BOOLEAN NOT NULL DEFAULT FALSE,
 starts_at TIMESTAMPTZ,ends_at TIMESTAMPTZ,
 request_key UUID NOT NULL UNIQUE,legacy_key VARCHAR(40) UNIQUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),version BIGINT NOT NULL DEFAULT 0,
 CHECK(starts_at IS NULL OR ends_at IS NULL OR starts_at<ends_at),
 CHECK((mobile_image_url IS NULL AND mobile_image_public_id IS NULL AND mobile_width IS NULL AND mobile_height IS NULL) OR (mobile_image_url IS NOT NULL AND mobile_image_public_id IS NOT NULL AND mobile_width>0 AND mobile_height>0))
);
CREATE INDEX IF NOT EXISTS idx_promotional_banner_publication ON promotional_banner(active,sort_order,id);
CREATE TABLE IF NOT EXISTS promotional_banner_seed (seed_key VARCHAR(40) PRIMARY KEY,applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
COMMIT;
